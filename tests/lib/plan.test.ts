import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { formulateAnalysisPlan, InvalidPlanColumnError } from '../../src/lib/dataset/plan.js';

describe('Analysis Plan Contract Engine', () => {
  const testDir = path.resolve(process.cwd(), 'tests/fixtures/plan_sandbox');
  const planCsv = path.join(testDir, 'sales_plan_sample.csv');

  beforeAll(() => {
    fs.mkdirSync(testDir, { recursive: true });
    const content = [
      'date,region,category,revenue,units_sold',
      '2024-01-01,North,Electronics,1200.50,10',
      '2024-01-02,South,Apparel,450.00,15',
    ].join('\n');
    fs.writeFileSync(planCsv, content);
  });

  afterAll(() => {
    if (fs.existsSync(testDir)) {
      fs.rmSync(testDir, { recursive: true, force: true });
    }
  });

  it('generates a valid analysis plan grounded against dataset columns', async () => {
    const plan = await formulateAnalysisPlan({
      datasetPath: 'sales_plan_sample.csv',
      customBaseDir: testDir,
      businessQuestion: 'What is the total revenue by region for January 2024?',
      primaryObjective: 'Calculate regional revenue breakdown and units sold',
      requiredColumns: ['region', 'revenue', 'units_sold'],
      targetMetrics: [
        {
          name: 'total_revenue',
          description: 'Sum of revenue generated by region',
          formulaOrAggregation: 'SUM(revenue)',
          unit: 'USD',
        },
        {
          name: 'total_units',
          description: 'Sum of units sold',
          formulaOrAggregation: 'SUM(units_sold)',
          unit: 'units',
        },
      ],
      groupingDimensions: ['region'],
      filters: ["date >= '2024-01-01'"],
      plannedSteps: [
        'Filter records to January 2024',
        'Group by region',
        'Calculate sum of revenue and units_sold',
        'Sort descending by total revenue',
      ],
      assumptions: ['Revenue is recorded net of standard discounts in USD'],
      unresolvedAmbiguities: ['Are returns deducted from revenue in this table?'],
    });

    expect(plan.planId).toMatch(/^plan_/);
    expect(plan.datasetPath).toBe('sales_plan_sample.csv');
    expect(plan.businessQuestion).toBe('What is the total revenue by region for January 2024?');
    expect(plan.status).toBe('draft_plan_pending_execution');
    expect(plan.requiredColumns).toEqual(['region', 'revenue', 'units_sold']);
    expect(plan.groupingDimensions).toEqual(['region']);
    expect(plan.targetMetrics.length).toBe(2);
    expect(plan.assumptions.length).toBe(1);
    expect(plan.unresolvedAmbiguities.length).toBe(1);
    expect(plan.createdAt).toBeDefined();
  });

  it('rejects plan when required columns do not exist in the dataset', async () => {
    await expect(
      formulateAnalysisPlan({
        datasetPath: 'sales_plan_sample.csv',
        customBaseDir: testDir,
        businessQuestion: 'What is the gross margin?',
        primaryObjective: 'Calculate gross margin',
        requiredColumns: ['revenue', 'cogs_cost_of_goods_sold'], // Non-existent column
        targetMetrics: [
          {
            name: 'gross_margin',
            description: 'Revenue minus COGS',
          },
        ],
        plannedSteps: ['Subtract COGS from Revenue'],
      })
    ).rejects.toThrow(InvalidPlanColumnError);
  });

  it('rejects plan when grouping dimension column does not exist in dataset', async () => {
    await expect(
      formulateAnalysisPlan({
        datasetPath: 'sales_plan_sample.csv',
        customBaseDir: testDir,
        businessQuestion: 'What is revenue by store manager?',
        primaryObjective: 'Breakdown revenue by store manager',
        requiredColumns: ['revenue'],
        groupingDimensions: ['store_manager'], // Non-existent column
        targetMetrics: [
          {
            name: 'total_revenue',
            description: 'Sum of revenue',
          },
        ],
        plannedSteps: ['Group by store_manager and sum revenue'],
      })
    ).rejects.toThrow(InvalidPlanColumnError);
  });
});
